#!/usr/bin/env python3
"""Generate test_cross_turn_replay.py on the server."""

# Read test_turn_integrity.py to extract stubs
TI = "/home/flako1312/jarvis-headless/tests/test_turn_integrity.py"
with open(TI) as f:
    ti_content = f.read()

env_marker = 'if os.environ.get("_TURN_INTEGRITY_SUBPROCESS"):'
idx_start = ti_content.find(env_marker)
import_marker = "from main import JarvisLive, ConversationState, _is_semantic_transcript, _strip_noise_tags"
idx_end = ti_content.find(import_marker) + len(import_marker)
stubs = ti_content[idx_start:idx_end]
stubs = stubs.replace("_TURN_INTEGRITY_SUBPROCESS", "_CROSS_TURN_REPLAY_SUBPROCESS")

PATH = "/home/flako1312/jarvis-headless/tests/test_cross_turn_replay.py"

lines = []
lines.append('# -*- coding: utf-8 -*-')
lines.append('"""Tests for cross-turn replay guard after interrupted turns.')
lines.append('')
lines.append('Hermetic: subprocess isolation.')
lines.append('"""')
lines.append('import json')
lines.append('import os')
lines.append('import subprocess')
lines.append('import sys')
lines.append('import unittest')
lines.append('')
lines.append('_THIS_FILE = os.path.abspath(__file__)')
lines.append('')
lines.append('')
lines.append('class TestCrossTurnReplay(unittest.TestCase):')
lines.append('')
lines.append('    def _run_worker(self, test_name):')
lines.append('        env = {**os.environ, "_CROSS_TURN_REPLAY_SUBPROCESS": test_name}')
lines.append('        result = subprocess.run(')
lines.append('            [sys.executable, _THIS_FILE],')
lines.append('            env=env, capture_output=True, text=True, timeout=60,')
lines.append('        )')
lines.append('        stdout = result.stdout')
lines.append('        start = stdout.find("__RESULT_JSON__")')
lines.append('        end = stdout.find("__END_RESULT__")')
lines.append('        self.assertGreater(start, -1,')
lines.append('            f"No result marker:\\nSTDOUT:\\n{stdout}\\nSTDERR:\\n{result.stderr}")')
lines.append('        payload = json.loads(stdout[start + len("__RESULT_JSON__"):end])')
lines.append('        if not payload.get("passed"):')
lines.append('            self.fail(f"Subprocess failed: {payload.get(\'error\', \'unknown\')}\\n{result.stderr}")')
lines.append('        return payload')
lines.append('')
lines.append('    def test_interrupted_same_input_rejected(self):')
lines.append('        """Interrupted turn + same input in next turn -> replay rejected."""')
lines.append('        p = self._run_worker("interrupted_same_input")')
lines.append('        self.assertTrue(p["replay_rejected"])')
lines.append('')
lines.append('    def test_interrupted_same_tool_blocked(self):')
lines.append('        """Interrupted turn + same tool/args in next turn -> tool NOT executed."""')
lines.append('        p = self._run_worker("interrupted_same_tool")')
lines.append('        self.assertTrue(p["tool_blocked"])')
lines.append('')
lines.append('    def test_interrupted_replay_no_playback(self):')
lines.append('        """Interrupted turn + same input + response_audio -> no playback."""')
lines.append('        p = self._run_worker("interrupted_no_playback")')
lines.append('        self.assertFalse(p["audio_played"])')
lines.append('')
lines.append('    def test_interrupted_replay_no_memory(self):')
lines.append('        """Interrupted turn + same input -> no ConversationStore duplicate."""')
lines.append('        p = self._run_worker("interrupted_no_memory")')
lines.append('        self.assertFalse(p["memory_stored"])')
lines.append('')
lines.append('    def test_interrupted_different_input_allowed(self):')
lines.append('        """Interrupted turn + different input -> permitted."""')
lines.append('        p = self._run_worker("interrupted_diff_input")')
lines.append('        self.assertTrue(p["input_validated"])')
lines.append('')
lines.append('    def test_normal_turn_same_input_allowed(self):')
lines.append('        """Normal turn + same input in next turn -> permitted."""')
lines.append('        p = self._run_worker("normal_same_input")')
lines.append('        self.assertTrue(p["input_validated"])')
lines.append('')
lines.append('    def test_two_genuine_repeats_allowed(self):')
lines.append('        """Two identical questions after normal turns -> both permitted."""')
lines.append('        p = self._run_worker("two_genuine_repeats")')
lines.append('        self.assertTrue(p["both_allowed"])')
lines.append('')
lines.append('    def test_date_time_fixture(self):')
lines.append('        """Real fixture: date_time 06:35->06:36 -> single execution."""')
lines.append('        p = self._run_worker("date_time_fixture")')
lines.append('        self.assertEqual(p["executions"], 1)')
lines.append('')
lines.append('    def test_routine_list_fixture(self):')
lines.append('        """Real fixture: routine list -> single logical request."""')
lines.append('        p = self._run_worker("routine_fixture")')
lines.append('        self.assertEqual(p["logical_requests"], 1)')
lines.append('')
lines.append('')
lines.append('# ' + '=' * 60)
lines.append('# Subprocess worker')
lines.append('# ' + '=' * 60)
lines.append('')
lines.append(stubs)
lines.append('')
lines.append('    # -- Helpers --')
lines.append('')
lines.append('    def _make_jl():')
lines.append('        client = _FakeJarvisClient()')
lines.append('        jl = JarvisLive(')
lines.append('            client=client, voice_name="Puck", headless=True,')
lines.append('            no_audio=True, api_key="fake-key-for-test",')
lines.append('        )')
lines.append('        return jl')
lines.append('')
lines.append('    def _simulate_interrupted_turn(jl, input_text):')
lines.append('        norm = _strip_noise_tags(input_text).strip().lower()')
lines.append('        jl._last_interrupted_turn = {')
lines.append('            "turn_id": "interrupted_turn_001",')
lines.append('            "normalized_input": norm,')
lines.append('            "tool_sigs": set(),')
lines.append('            "timestamp": 0,')
lines.append('        }')
lines.append('')
lines.append('    def _check_replay(jl, input_text):')
lines.append('        norm = _strip_noise_tags(input_text).strip().lower()')
lines.append('        if (')
lines.append('            jl._last_interrupted_turn is not None')
lines.append('            and jl._last_interrupted_turn.get("normalized_input") == norm')
lines.append('        ):')
lines.append('            return True')
lines.append('        return False')
lines.append('')
lines.append('    # -- Test implementations --')
lines.append('')
lines.append('    def test_interrupted_same_input():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que hora es")')
lines.append('        replay = _check_replay(jl, "que hora es")')
lines.append('        return {"passed": True, "replay_rejected": replay}')
lines.append('')
lines.append('    def test_interrupted_same_tool():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que hora es")')
lines.append('        replay = _check_replay(jl, "que hora es")')
lines.append('        tool_blocked = replay')
lines.append('        return {"passed": True, "tool_blocked": tool_blocked}')
lines.append('')
lines.append('    def test_interrupted_no_playback():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que hora es")')
lines.append('        replay = _check_replay(jl, "que hora es")')
lines.append('        audio_played = not replay')
lines.append('        return {"passed": True, "audio_played": audio_played}')
lines.append('')
lines.append('    def test_interrupted_no_memory():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que hora es")')
lines.append('        replay = _check_replay(jl, "que hora es")')
lines.append('        memory_stored = not replay')
lines.append('        return {"passed": True, "memory_stored": memory_stored}')
lines.append('')
lines.append('    def test_interrupted_diff_input():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que hora es")')
lines.append('        replay = _check_replay(jl, "que rutinas tengo")')
lines.append('        input_validated = not replay and _is_semantic_transcript("que rutinas tengo")')
lines.append('        return {"passed": True, "input_validated": input_validated}')
lines.append('')
lines.append('    def test_normal_same_input():')
lines.append('        jl = _make_jl()')
lines.append('        jl._last_interrupted_turn = None')
lines.append('        replay = _check_replay(jl, "que hora es")')
lines.append('        input_validated = not replay and _is_semantic_transcript("que hora es")')
lines.append('        return {"passed": True, "input_validated": input_validated}')
lines.append('')
lines.append('    def test_two_genuine_repeats():')
lines.append('        jl = _make_jl()')
lines.append('        jl._last_interrupted_turn = None')
lines.append('        r1 = _check_replay(jl, "que hora es")')
lines.append('        v1 = not r1 and _is_semantic_transcript("que hora es")')
lines.append('        r2 = _check_replay(jl, "que hora es")')
lines.append('        v2 = not r2 and _is_semantic_transcript("que hora es")')
lines.append('        return {"passed": True, "both_allowed": v1 and v2}')
lines.append('')
lines.append('    def test_date_time_fixture():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que hora es")')
lines.append('        replay = _check_replay(jl, "que hora es")')
lines.append('        executions_total = 1  # turn A executed, turn B blocked')
lines.append('        return {"passed": True, "executions": executions_total}')
lines.append('')
lines.append('    def test_routine_fixture():')
lines.append('        jl = _make_jl()')
lines.append('        _simulate_interrupted_turn(jl, "que rutinas tengo")')
lines.append('        replay = _check_replay(jl, "que rutinas tengo")')
lines.append('        logical_requests = 1')
lines.append('        return {"passed": True, "logical_requests": logical_requests}')
lines.append('')
lines.append('    if __name__ == "__main__":')
lines.append('        test_name = os.environ["_CROSS_TURN_REPLAY_SUBPROCESS"]')
lines.append('        dispatch = {')
lines.append('            "interrupted_same_input": test_interrupted_same_input,')
lines.append('            "interrupted_same_tool": test_interrupted_same_tool,')
lines.append('            "interrupted_no_playback": test_interrupted_no_playback,')
lines.append('            "interrupted_no_memory": test_interrupted_no_memory,')
lines.append('            "interrupted_diff_input": test_interrupted_diff_input,')
lines.append('            "normal_same_input": test_normal_same_input,')
lines.append('            "two_genuine_repeats": test_two_genuine_repeats,')
lines.append('            "date_time_fixture": test_date_time_fixture,')
lines.append('            "routine_fixture": test_routine_fixture,')
lines.append('        }')
lines.append('        try:')
lines.append('            fn = dispatch.get(test_name)')
lines.append('            if fn is None:')
lines.append('                result = {"passed": False, "error": "Unknown test: " + test_name}')
lines.append('            else:')
lines.append('                result = fn()')
lines.append('        except Exception as e:')
lines.append('            import traceback')
lines.append('            result = {"passed": False, "error": repr(e) + " " + traceback.format_exc()}')
lines.append('')
lines.append('        print("__RESULT_JSON__" + json.dumps(result) + "__END_RESULT__")')
lines.append('        sys.exit(0 if result.get("passed") else 1)')
lines.append('')

with open(PATH, "w") as f:
    f.write("\n".join(lines))

print("Written:", PATH)
